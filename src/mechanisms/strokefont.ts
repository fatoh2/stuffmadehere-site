/** Strokes for a text line placed at (x, y) top-left with a cap height of `size` px. */
export function strokesFor(text: string, x: number, y: number, size: number): number[][][] {
  const s = size / 6;
  const adv = 5.6 * s;
  const out: number[][][] = [];
  let cx = x;
  for (const ch of text.toUpperCase()) {
    if (ch === ' ') {
      cx += adv * 0.7;
      continue;
    }
    const g = G[ch];
    if (g) for (const st of g) out.push(st.map(([px, py]) => [cx + px * s, y + py * s]));
    cx += adv;
  }
  return out;
}

export function textWidth(text: string, size: number): number {
  const s = size / 6;
  const adv = 5.6 * s;
  let w = 0;
  for (const ch of text) w += ch === ' ' ? adv * 0.7 : adv;
  return w;
}
